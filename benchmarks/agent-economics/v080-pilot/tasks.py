#!/usr/bin/env python3
"""Generate the four bounded fixtures for the v0.8 Haiku A/B pilot.

The source strings are deliberately kept here, rather than in generated files, so a
manifest can be regenerated byte-for-byte and the runner can use its preserve-source
path. The manifest includes identical project check/configuration files for both
arms; hidden oracle checksums protect these support files from candidate edits.
"""

from __future__ import annotations

