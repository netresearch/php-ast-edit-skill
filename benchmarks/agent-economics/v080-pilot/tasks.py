CONFUSABLE = php(
    r"""
    <?php

    declare(strict_types=1);

    namespace Pilot\Confusable;

    /** Demonstrates a parameter capture beside a property and method of the same name. */
    final class Ledger
    {
        public function __construct(private readonly int $total)
        {
        }

        public function total(): int
        {
            return $this->total;
        }

        public function receipt(int $total): array
        {
            $capture = static function (int $line) use ($total): int {
                return $total + $line;
            };
            $sum = $capture(3);

            return [
                'total' => $sum,
                'label' => 'total',
            ];
        }

        public function unchangedParameter(int $total): int
        {
            return $total + 1;
        }

        public function callableReceipt(int $total): int
        {
            $make = fn (int $line): int => $total + $line;

            return $make(2);
        }
    }

    function receiptValues(): array
    {
        $ledger = new Ledger(100);

        return [
            $ledger->total(),
            $ledger->receipt(5),
            $ledger->unchangedParameter(5),
            $ledger->callableReceipt(5),
        ];
    }
    """
)


def task(
    identifier: str,
    prompt: str,
    files: dict[str, str],
    edits: list[dict[str, Any]],
    oracle: str,
) -> dict[str, Any]:
    entries = dict(files)
    entries.update(SUPPORT[identifier])
    support_hashes = {
        path: hashlib.sha256(source.encode("utf-8")).hexdigest()
        for path, source in SUPPORT[identifier].items()
    }
    support_array = (
        "["
        + ", ".join(
            f"'{path}'=>'{checksum}'" for path, checksum in support_hashes.items()
        )
        + "]"
    )
    guard = (
        "$supportHashes = "
        + support_array
        + "; foreach ($supportHashes as $supportFile => $supportHash) { if (!is_file($supportFile) || hash_file('sha256', $supportFile) !== $supportHash) { exit(1); } } "
    )
    return {
        "id": identifier,
        "prompt": prompt,
        "files": [{"path": path, "php": source} for path, source in entries.items()],
        "preserve_source": True,
        "outcome": "changed",
        "edits": edits,
        "oracle": guard + oracle,
    }


