def php(source: str) -> str:
    """Normalize an embedded fixture without changing its PHP bytes semantically."""

    return textwrap.dedent(source).lstrip() + "\n"


SIMPLE = php(
    r"""
    <?php

    declare(strict_types=1);

    namespace Pilot\Simple;

    /** A small greeting value object used by a command-line renderer. */
    final class Greeting
    {
        public function __construct(private readonly string $name)
        {
        }

        public function greeting(): string
        {
            return 'Hello ' . $this->name;
        }

        public function initials(): string
        {
            return strtoupper($this->name[0]);
        }

        public function label(): string
        {
            return 'greeting';
        }

        public function asArray(): array
        {
            return [
                'name' => $this->name,
                'greeting' => $this->greeting(),
                'initials' => $this->initials(),
            ];
        }
    }

    function renderGreeting(string $name): array
    {
        $greeting = new Greeting($name);

        return $greeting->asArray();
    }

    function renderLabel(): string
    {
        return (new Greeting('Ada'))->label();
    }

    function renderInitials(string $name): string
    {
        return (new Greeting($name))->initials();
    }
    """
)


SAME_FILE_BATCH = php(
    r"""
    <?php

    declare(strict_types=1);

    namespace Pilot\Batch;

    /** A cart with three calculations that intentionally use the same local name. */
    final class Cart
    {
        public function __construct(
            private readonly int $price,
            private readonly int $fee,
        ) {
        }

        public function subtotal(): int
        {
            $value = $this->price + $this->fee;

            return $value;
        }

        public function tax(): int
        {
            $value = intdiv($this->subtotal() * 2, 10);

            return $value;
        }

        public function total(): int
        {
            $value = $this->subtotal() + $this->tax();

            return $value;
        }

        public function propertyValue(): int
        {
            return $this->price;
        }

        public function label(): string
        {
            return 'value';
        }

        public function summary(): array
        {
            return [
                'subtotal' => $this->subtotal(),
                'tax' => $this->tax(),
                'total' => $this->total(),
            ];
        }
    }

    function buildCart(): array
    {
        return (new Cart(10, 5))->summary();
    }
    """
)


AUTOLOAD = php(
    r"""
    <?php

    declare(strict_types=1);

    spl_autoload_register(static function (string $class): void {
        $prefix = 'Pilot\\CrossFile\\';

        if (!str_starts_with($class, $prefix)) {
            return;
        }

        $relative = substr($class, strlen($prefix));
        $file = __DIR__ . '/src/' . str_replace('\\', '/', $relative) . '.php';

        if (is_file($file)) {
            require_once $file;
        }
    });
    """
)


